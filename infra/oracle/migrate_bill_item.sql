-- The dump predates the billing fields. Add them before Hibernate uses BILL_ITEM.
DECLARE
    PROCEDURE add_column_if_missing(column_name_in VARCHAR2, definition_in VARCHAR2) IS
        column_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO column_count
        FROM ALL_TAB_COLUMNS
        WHERE OWNER = 'HOSPITAL' AND TABLE_NAME = 'BILL_ITEM' AND COLUMN_NAME = column_name_in;
        IF column_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE HOSPITAL.BILL_ITEM ADD (' || definition_in || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('ITEM_CATEGORY', 'ITEM_CATEGORY VARCHAR2(30)');
    add_column_if_missing('QUANTITY', 'QUANTITY NUMBER(10)');
    add_column_if_missing('UNIT_PRICE', 'UNIT_PRICE NUMBER(10)');
END;
/

UPDATE HOSPITAL.BILL_ITEM
SET ITEM_CATEGORY = COALESCE(ITEM_CATEGORY, 'ETC'),
    QUANTITY = COALESCE(QUANTITY, 1),
    UNIT_PRICE = COALESCE(UNIT_PRICE, ITEM_AMOUNT)
WHERE ITEM_CATEGORY IS NULL OR QUANTITY IS NULL OR UNIT_PRICE IS NULL;

BEGIN
    FOR col IN (
        SELECT COLUMN_NAME FROM ALL_TAB_COLUMNS
        WHERE OWNER = 'HOSPITAL' AND TABLE_NAME = 'BILL_ITEM' AND NULLABLE = 'Y'
          AND COLUMN_NAME IN ('ITEM_CATEGORY', 'QUANTITY', 'UNIT_PRICE')
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE HOSPITAL.BILL_ITEM MODIFY (' || col.COLUMN_NAME || ' NOT NULL)';
    END LOOP;
END;
/
COMMIT;
EXIT;
