WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
    table_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO table_count FROM ALL_TABLES
    WHERE OWNER = 'HOSPITAL' AND TABLE_NAME = 'KAKAOPAY_ATTEMPT';
    IF table_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE HOSPITAL.KAKAOPAY_ATTEMPT (
            ORDER_ID VARCHAR2(36) PRIMARY KEY,
            BILL_ID NUMBER NOT NULL REFERENCES HOSPITAL.BILL (BILL_ID),
            TID VARCHAR2(100) NOT NULL UNIQUE,
            AMOUNT NUMBER(10) NOT NULL,
            RECORDED NUMBER(1) DEFAULT 0 NOT NULL
        )';
    END IF;
END;
/
EXIT;
