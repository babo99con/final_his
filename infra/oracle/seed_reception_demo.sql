WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- The reservation rules and schedules reference the numeric DEPARTMENTS and STAFF keys.
INSERT INTO HOSPITAL.DEPARTMENTS (ID, NAME, IS_ACTIVE, SORT_ORDER, CREATED_AT)
SELECT 1, d.DEPARTMENT_NAME, 'Y', 1, SYSDATE
FROM HOSPITAL.STAFF_DEPARTMENT d
WHERE d.DEPARTMENT_ID = '1'
  AND d.RECEPTION_DISPLAY_YN = 'Y'
  AND NOT EXISTS (SELECT 1 FROM HOSPITAL.DEPARTMENTS existing WHERE existing.ID = 1);

-- The reception doctor list looks up active DOC-* codes in CMH_STAFF.
INSERT INTO HOSPITAL.CMH_STAFF (
    ID, USERNAME, FULL_NAME, DOMAIN_ROLE, STATUS, CREATED_AT,
    STAFF_ID, STAFF_DEPARTMENT_ID, EMPLOYMENT_STATUS
)
SELECT 919901, 'demo-reception-doctor', 'Demo Doctor', 'DOCTOR', 'ACTIVE', SYSDATE,
       'DOC-DEMO-001', d.DEPARTMENT_ID, 'ACTIVE'
FROM HOSPITAL.STAFF_DEPARTMENT d
WHERE d.DEPARTMENT_ID = '1'
  AND d.RECEPTION_DISPLAY_YN = 'Y'
  AND NOT EXISTS (
      SELECT 1 FROM HOSPITAL.CMH_STAFF existing WHERE existing.STAFF_ID = 'DOC-DEMO-001'
  );

-- Keep the same numeric key for the demo doctor across both staff tables.
INSERT INTO HOSPITAL.STAFF (
    ID, USERNAME, FULL_NAME, DOMAIN_ROLE, DEPT_ID, CREATED_AT, STAFF_ID, ACTIVE_YN, STAFF_NAME
)
SELECT s.ID, s.USERNAME, s.FULL_NAME, s.DOMAIN_ROLE, d.ID, SYSDATE, s.ID, 'Y', s.FULL_NAME
FROM HOSPITAL.CMH_STAFF s
JOIN HOSPITAL.DEPARTMENTS d ON d.ID = 1
WHERE s.ID = 919901
  AND s.STAFF_ID = 'DOC-DEMO-001'
  AND s.STAFF_DEPARTMENT_ID = '1'
  AND NOT EXISTS (SELECT 1 FROM HOSPITAL.STAFF existing WHERE existing.ID = s.ID);

COMMIT;
EXIT;
